"""รูปหลายใบที่คนส่งทีเดียว — รอให้ชุดครบก่อนค่อยตอบครั้งเดียว

คนเลือกรูป 3 ใบแล้วกดส่งทีเดียว เขาเห็นว่าตัวเองส่ง **หนึ่งครั้ง** แต่ของมาถึงเรา
ทีละใบเป็นคนละงานกัน การซอยเป็นสามครั้งเป็นเรื่องภายในของช่องทางแชท ไม่ใช่สิ่งที่เขาทำ

ถ้าตอบทุกใบที่มาถึง เขาจะโดนเด้ง 3 ข้อความจากการกดส่งครั้งเดียว ตัวนี้เลยให้แต่ละใบ
รอสักครู่แล้วดูว่ามีใบตามมาอีกไหม **ใบสุดท้ายเท่านั้นที่ได้พูด** ใบก่อนหน้าถอยออกไปเงียบ ๆ

ตัวนับอยู่ใน Redis ไม่ใช่ในหน่วยความจำของ process — ขึ้นหลาย process แล้วยังนับชุดเดียวกันได้
"""

import asyncio

from redis.asyncio import Redis

WAIT_SECONDS = 4    # รอใบถัดไปนานเท่านี้ ส่งรวดจากมือถือมาห่างกันไม่ถึงวินาที
KEEP_SECONDS = 60   # ตัวนับอยู่ได้เท่านี้ เผื่อใบสุดท้ายตายกลางทางจะได้ไม่ค้าง


def _key(session_id: str) -> str:
    return f"burst:{session_id}"


async def settled(r: Redis, session_id: str) -> int:
    """คืนจำนวนรูปในชุดถ้าเราคือใบสุดท้าย คืน 0 ถ้ามีใบใหม่ตามมาแล้ว

    ได้ 0 แปลว่า "เงียบไว้ เดี๋ยวใบหลังพูดแทน" ไม่ได้แปลว่าผิดพลาด
    """
    key = _key(session_id)

    mine = await r.incr(key)
    await r.expire(key, KEEP_SECONDS)

    await asyncio.sleep(WAIT_SECONDS)

    if int(await r.get(key) or 0) != mine:
        return 0

    await r.delete(key)
    return mine
